"""Guard tests for carrying RC6 onto new edits, using explicitly synthetic ROMs.

Real-ROM identity, fresh reconstruction and emulator evidence are generated by
the release/QA commands. These tests need neither a commercial ROM nor a save.
"""
import importlib.util
from pathlib import Path
import unittest


ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("qa14_chipcontrol", ROOT / "scripts/qa14_chipcontrol.py")
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)


def checked(blob):
    data = bytearray(blob)
    data[-2:] = (sum(data[:-2]) & 0xFFFF).to_bytes(2, "little")
    return bytes(data)


class CarryRC6Tests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        legacy = module.adapter()
        patch = (module.CC / "vendor/ChipControl_v0.5.8_RC6_for_English_v0.10.7-graphics-a9.ips").read_bytes()
        legacy.require_equal(module.digest(patch), legacy.RC6_IPS_SHA, "test RC6 IPS")
        cls.records = legacy.parse_ips(patch)
        data = bytearray(module.ROM_SIZE)
        cls.offsets = set()
        for start, payload in cls.records:
            for offset, target in enumerate(payload, start):
                if offset < module.CHECKSUM_START:
                    # Distinct synthetic preimage at every real write offset.
                    data[offset] = target ^ 0x80
                    cls.offsets.add(offset)
        cls.base = checked(data)

    def test_preserves_new_outside_edit_and_recomputes_checksum(self):
        edited = bytearray(self.base)
        self.assertNotIn(0x120000, self.offsets)
        edited[0x120000] = 0x63
        edited = checked(edited)
        result, report = module._carry_delta(edited, self.base, self.base, self.records)
        self.assertEqual(result[0x120000], 0x63)
        self.assertEqual(report["functional_bytes_changed"], 1959)
        self.assertEqual(report["english_changes_preserved"], 1)
        module.valid_checksum(result, "test output")
        self.assertEqual(edited[0x120000], 0x63)

    def test_conflicting_new_edit_is_rejected_before_mutation(self):
        edited = bytearray(self.base)
        offset = min(self.offsets)
        edited[offset] ^= 1
        edited = checked(edited)
        before = module.digest(edited)
        with self.assertRaisesRegex(ValueError, "RC6 functional conflict"):
            module._carry_delta(edited, self.base, self.base, self.records)
        self.assertEqual(module.digest(edited), before)

    def test_double_application_is_rejected(self):
        once, _ = module._carry_delta(self.base, self.base, self.base, self.records)
        with self.assertRaisesRegex(ValueError, "RC6 functional conflict"):
            module._carry_delta(once, self.base, self.base, self.records)

    def test_invalid_checksum_is_rejected(self):
        broken = bytearray(self.base)
        broken[-1] ^= 1
        with self.assertRaisesRegex(ValueError, "checksum"):
            module._carry_delta(bytes(broken), self.base, self.base, self.records)

    def test_unchanged_ips_hole_inside_consumed_payload_is_protected(self):
        start, end, _ = module.RESERVED_REGIONS[1]
        offset = next(i for i in range(start, end) if i not in self.offsets)
        edited = bytearray(self.base)
        edited[offset] ^= 1
        with self.assertRaisesRegex(ValueError, "reserved-region conflict"):
            module._carry_delta(checked(edited), self.base, self.base, self.records)

    def test_wrong_parent_identity_is_rejected(self):
        with self.assertRaisesRegex(ValueError, "MANT04 English reference SHA-256 mismatch"):
            module.apply(self.base, self.base, self.base)

    def test_overlap_and_wrong_write_count_are_rejected(self):
        overlap = list(self.records)
        overlap[1] = overlap[0]
        with self.assertRaisesRegex(ValueError, "Overlapping RC6 record"):
            module._carry_delta(self.base, self.base, self.base, overlap)
        with self.assertRaisesRegex(ValueError, "record count"):
            module._carry_delta(self.base, self.base, self.base, self.records[:-1])


if __name__ == "__main__":
    unittest.main()
