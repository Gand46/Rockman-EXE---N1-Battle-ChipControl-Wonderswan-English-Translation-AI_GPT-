#!/usr/bin/env python3
"""Capture the actual WS renderer from a cold SRAM boot, then button-only routes.

The optional QA core and private seed SRAM are external CLI inputs. All new
states are generated by the selected ROM after cold Continue; no stale VRAM
from earlier releases is accepted. Output contains private diagnostic states.
"""
from __future__ import annotations
import argparse, hashlib, json, os, shutil, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CAPTURE = ROOT / 'components/qa09/src/qa09_capture.py'

def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()

def tap(key, wait=30, name=None):
    tail = {'frames': wait}
    if name: tail['name'] = name
    return [{'frames': 6, 'keys': [key]}, tail]

def capture(rom, engine, output, case, steps, *, state=None, sram=None, save=None):
    rom, engine, output = Path(rom).resolve(), Path(engine).resolve(), Path(output).resolve()
    source_before = sha(rom)
    output.mkdir(parents=True, exist_ok=True)
    if state and sram: raise ValueError('Cold SRAM and savestate are mutually exclusive')
    if not steps or sum(int(s['frames']) for s in steps) > 50000:
        raise ValueError('Route exceeds frame budget')
    if any('poke' in s or 'allowed_addresses' in s for s in steps):
        raise ValueError('This menu route accepts only controller inputs')
    route = output / (case + '.route.json')
    route.write_text(json.dumps(steps, indent=2) + '\n')
    roms = output / 'roms'; roms.mkdir(exist_ok=True)
    staged = roms / 'game.wsc'; shutil.copyfile(rom, staged)
    env = dict(os.environ, QA_ENGINE_DIR=str(engine), AUDIT_ROM_DIR=str(roms), QA_CAPTURE_DIR=str(output))
    command = [sys.executable, str(CAPTURE), 'game', str(route), str(state) if state else '-',
               str(sram) if sram else '-', str(save) if save else '-']
    with (output / (case + '.log')).open('w') as log:
        subprocess.run(command, env=env, stdout=log, stderr=subprocess.STDOUT, timeout=90, check=True)
    staged.unlink(); roms.rmdir()
    if sha(rom) != source_before:
        raise ValueError('Source ROM changed during capture')
    shots = []
    for s in steps:
        if 'name' in s:
            p = output / ('game_' + s['name'] + '.png')
            from PIL import Image
            with Image.open(p) as im:
                if im.size != (224, 144): raise ValueError('Non-native screenshot dimensions')
            shots.append({'name': s['name'], 'png': p.name, 'sha256': sha(p),
                          'state_sha256': sha(p.with_suffix('.state')), 'ram_sha256': sha(p.with_suffix('.ram'))})
    report = {'case': case, 'rom_sha256': sha(rom), 'emulator_core_sha256': sha(engine/'emulator/mednafen_wswan_libretro.so'),
              'route_sha256': sha(route), 'frames': sum(s['frames'] for s in steps),
              'access': 'SCRIPTED_NATURAL_FROM_COLD_SRAM' if sram else 'SAVESTATE_GENERATED_IN_SAME_ROM',
              'seed_sram_sha256': sha(sram) if sram else None, 'input_state_sha256': sha(state) if state else None,
              'output_sram_sha256': sha(save) if save else None, 'screenshots': shots,
              'wram_pokes': 0, 'source_rom_unchanged': True}
    (output / (case + '.json')).write_text(json.dumps(report, indent=2) + '\n')
    return report

def suite(rom, engine, output, seed):
    out = Path(output).resolve(); out.mkdir(parents=True, exist_ok=True)
    reports = []
    cold = [{'frames': 420}] + tap('start',180,'title_continue') + tap('start',360,'carousel_pet') + tap('a',180,'root_0')
    reports.append(capture(rom,engine,out/'cold','cold',cold,sram=seed,save=out/'cold_unchanged.srm'))
    root = out/'cold/game_root_0.state'
    carousel = out/'cold/game_carousel_pet.state'
    route=[]
    for name in ['shop','gp','free','host','pet_return']:
        route += tap('right',180,'carousel_'+name)
    reports.append(capture(rom,engine,out/'carousel','carousel',route,state=carousel))
    route=[{'frames':30,'name':'root_0'}]
    for i in range(1,5): route += tap('down',30,'root_'+str(i))
    reports.append(capture(rom,engine,out/'menu','menu',route,state=root))
    for i, name in enumerate(['deck','folder','library','netnavi','save_panel']):
        route=[]
        for _ in range(i): route += tap('down')
        route += tap('a',180,name)
        reports.append(capture(rom,engine,out/name,name,route,state=root))
    route=tap('start',90,'sort_0')
    for i in range(1,7): route += tap('right',30,'sort_'+str(i))
    reports.append(capture(rom,engine,out/'sort','sort',route,state=out/'folder/game_folder.state'))
    for i in range(7):
        route=[]
        for _ in range(i): route += tap('right',30)
        route += tap('a',90,'sort_applied_'+str(i))
        reports.append(capture(rom,engine,out/('sort_action_'+str(i)),'sort_action_'+str(i),route,
                               state=out/'sort/game_sort_0.state'))
    reports.append(capture(rom,engine,out/'shop','shop',tap('a',240,'shop_select_0'),
                           state=out/'carousel/game_carousel_shop.state'))
    shop=out/'shop/game_shop_select_0.state'
    route=tap('down',60,'shop_select_1')+tap('a',300,'shop_insufficient')+tap('a',120)
    route+=tap('down',90,'shop_select_2')+tap('a',300,'shop_info_action')
    reports.append(capture(rom,engine,out/'shop_branches','shop_branches',route,state=shop))
    route=tap('a',240,'purchase_confirm')+tap('a',240,'purchase_received')+tap('a',240,'purchase_menu')
    route+=tap('b',180,'shop_farewell')+tap('a',180,'shop_exited')+tap('left',180,'pet_after_purchase')
    route+=tap('a',180,'root_after_purchase')
    for _ in range(3): route+=tap('down',30)
    route+=tap('a',180,'netnavi_after_purchase')+tap('b',90,'root_before_reentry')
    route+=tap('a',180,'netnavi_reentry')+tap('b',90)+tap('down',30)+tap('a',420,'save_after_purchase')
    route+=tap('a',480,'purchase_saved')
    exported=out/'purchase_saved.srm'
    reports.append(capture(rom,engine,out/'purchase','purchase',route,state=shop,save=exported))
    reports.append(capture(rom,engine,out/'reload','reload',cold,sram=exported,save=out/'purchase_cold.srm'))
    route=[]
    for _ in range(3):route+=tap('down',30)
    route+=tap('a',180,'netnavi_cold_after_purchase')
    reports.append(capture(rom,engine,out/'reload_netnavi','reload_netnavi',route,
                           state=out/'reload/game_root_0.state'))
    summary={'status':'CAPTURED_REQUIRES_VISUAL_REVIEW','rom_sha256':sha(rom),'seed_sram_sha256':sha(seed),
             'no_prior_release_savestates_loaded':True,'reports':reports,
             'purchase_sram_exact_after_cold_load':exported.read_bytes()==(out/'purchase_cold.srm').read_bytes()}
    (out/'session.json').write_text(json.dumps(summary,indent=2)+'\n')
    return summary

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--rom',type=Path,required=True);p.add_argument('--engine',type=Path,required=True)
    p.add_argument('--output',type=Path,required=True);p.add_argument('--sram',type=Path,required=True)
    a=p.parse_args(); r=suite(a.rom,a.engine,a.output,a.sram)
    print(json.dumps({'status':r['status'],'cases':len(r['reports']),'screenshots':sum(len(x['screenshots']) for x in r['reports'])}))
